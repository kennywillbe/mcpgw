#[test]
fn query_reports_a_running_enabled_unit_and_where_it_lives() {
    let dir = tempfile::tempdir().unwrap();
    let unit_path = dir.path().join("mcpgw.service");
    std::fs::write(&unit_path, "placeholder").unwrap();
    let fake = Fake::new(vec![
        ("is-active", Ok(Ran::ok("active"))),
        ("is-enabled", Ok(Ran::ok("enabled"))),
        ("show-user", Ok(Ran::ok("Linger=no"))),
    ]);

    let status = query_with(&unit_path, &fake.exec(), env(&[("USER", "u")])).unwrap();

    assert!(status.installed);
    assert!(status.running);
    assert_eq!(status.unit_path, Some(unit_path));
    let detail = status.detail.unwrap();
    assert!(detail.contains("comes back at login"), "{detail}");
    assert!(detail.contains("loginctl enable-linger u"), "{detail}");
}

/// systemd exits non-zero for "inactive" and "disabled". Those are answers,
/// not failures, and reading them as failures would make `daemon status`
/// error out on the most ordinary state there is.
#[test]
fn an_inactive_disabled_unit_is_a_status_and_not_an_error() {
    let dir = tempfile::tempdir().unwrap();
    let unit_path = dir.path().join("mcpgw.service");
    std::fs::write(&unit_path, "placeholder").unwrap();
    let fake = Fake::new(vec![
        ("is-active", Ok(Ran::failed("inactive"))),
        ("is-enabled", Ok(Ran::ok("disabled"))),
    ]);

    let status = query_with(&unit_path, &fake.exec(), env(&[])).unwrap();

    assert!(status.installed);
    assert!(!status.running);
    assert!(
        status
            .detail
            .unwrap()
            .contains("will not come back at login"),
        "disabled has to be visible in status, not swallowed"
    );
}

