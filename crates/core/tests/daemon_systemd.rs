#[test]
fn linger_reads_the_property_and_treats_every_other_answer_as_unknown() {
    let cases = [
        (Ok(Ran::ok("Linger=yes")), Linger::On),
        (Ok(Ran::ok("Linger=no")), Linger::Off),
        (Ok(Ran::ok("")), Linger::Unknown),
        (
            Ok(Ran::failed("Failed to get user: No such user")),
            Linger::Unknown,
        ),
        (missing(), Linger::Unknown),
    ];

    for (reply, expected) in cases {
        let fake = Fake::new(vec![("show-user", reply)]);
        assert_eq!(linger(&fake.exec(), Some("u")), expected);
        assert_eq!(
            fake.calls(),
            ["loginctl show-user u --property=Linger".to_owned()]
        );
    }
}

