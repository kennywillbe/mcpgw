/// The note is the only place a user learns their gateway dies at logout, so
/// each of the three answers has to produce a different sentence — and the
/// two that are not "on" have to name the command that fixes it.
#[test]
fn the_linger_note_says_which_of_the_three_states_this_is() {
    let on = Fake::new(vec![("show-user", Ok(Ran::ok("Linger=yes")))]);
    let note = linger_note(&on.exec(), env(&[("USER", "u")]));
    assert!(note.contains("keeps running after you log out"), "{note}");
    assert!(!note.contains("enable-linger"), "{note}");

    let off = Fake::new(vec![("show-user", Ok(Ran::ok("Linger=no")))]);
    let note = linger_note(&off.exec(), env(&[("LOGNAME", "u")]));
    assert!(note.contains("stops when your last session ends"), "{note}");
    assert!(note.contains("loginctl enable-linger u"), "{note}");
    // Reporting, not doing: the note has to say mcpgw left the account alone.
    assert!(note.contains("does not run it for you"), "{note}");

    let absent = Fake::new(vec![("show-user", missing())]);
    let note = linger_note(&absent.exec(), env(&[]));
    assert!(note.contains("could not ask loginctl"), "{note}");
    assert!(note.contains("loginctl enable-linger $USER"), "{note}");
}

#[test]
fn the_unit_goes_where_systemctl_user_looks_for_it() {
    assert_eq!(
        unit_path_with(env(&[("XDG_CONFIG_HOME", "/xdg"), ("HOME", "/home/u")])),
        Some(PathBuf::from("/xdg/systemd/user/mcpgw.service"))
    );
    assert_eq!(
        unit_path_with(env(&[("HOME", "/home/u")])),
        Some(PathBuf::from("/home/u/.config/systemd/user/mcpgw.service"))
    );
    assert_eq!(
        unit_path_with(env(&[("XDG_CONFIG_HOME", ""), ("HOME", "/home/u")])),
        Some(PathBuf::from("/home/u/.config/systemd/user/mcpgw.service"))
    );
    assert_eq!(unit_path_with(env(&[])), None);
}
